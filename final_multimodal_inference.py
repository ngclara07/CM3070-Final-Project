def get_device() -> torch.device:
    return torch.device(
        "cuda"
        if torch.cuda.is_available()
        else "cpu"
    )


def confidence_level(
    gap: float,
) -> str:
    if gap >= 0.35:
        return "High"

    if gap >= 0.15:
        return "Medium"

    return "Low"


def safe_mean(
    values: list[float],
) -> float:
    return (
        statistics.mean(values)
        if values
        else 0.0
    )


def safe_std(
    values: list[float],
) -> float:
    return (
        statistics.stdev(values)
        if len(values) >= 2
        else 0.0
    )


def normalise_label(
    value: Any,
) -> str:
    if value is None:
        return ""

    return (
        str(value)
        .strip()
        .lower()
    )


def clean_float(
    value: Any,
) -> float:
    """
    Convert a value to finite float.
    """

    try:
        numeric = float(value)

        if np.isfinite(numeric):
            return numeric

    except Exception:
        pass

    return 0.0


def load_json_list(
    path: Path,
) -> list[str]:
    if not path.exists():
        return []

    try:
        with path.open(
            "r",
            encoding="utf-8",
        ) as f:
            value = json.load(f)

        if not isinstance(
            value,
            list,
        ):
            return []

        return [
            str(item)
            for item
            in value
        ]

    except Exception:
        return []


def get_model_classes(
    model: Any,
) -> list[str]:
    """
    Obtain class ordering from either a classifier or sklearn Pipeline.
    """

    classes = getattr(
        model,
        "classes_",
        None,
    )

    if classes is not None:
        return [
            normalise_label(label)
            for label
            in classes
        ]

    if hasattr(
        model,
        "named_steps",
    ):
        for step in reversed(
            list(
                model.named_steps.values()
            )
        ):
            classes = getattr(
                step,
                "classes_",
                None,
            )

            if classes is not None:
                return [
                    normalise_label(label)
                    for label
                    in classes
                ]

    return []


def softmax(
    values: np.ndarray,
) -> np.ndarray:
    values = np.asarray(
        values,
        dtype=float,
    )

    values = (
        values
        - np.max(values)
    )

    exp_values = np.exp(
        values
    )

    total = float(
        np.sum(exp_values)
    )

    if total <= 0:
        return (
            np.ones_like(exp_values)
            / len(exp_values)
        )

    return exp_values / total


