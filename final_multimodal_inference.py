def safe_mean(
    values: list[float],
) -> float:
    """
    Arithmetic mean with an empty-list fallback.
    """

    return (
        statistics.mean(
            values
        )
        if values
        else 0.0
    )


def safe_std(
    values: list[float],
) -> float:
    """
    Sample standard deviation with a small-sample fallback.
    """

    return (
        statistics.stdev(
            values
        )
        if len(values) >= 2
        else 0.0
    )


def normalise_label(
    value: Any,
) -> str:
    """
    Convert an arbitrary class label into the canonical textual format.
    """

    if value is None:

        return ""

    return (
        str(value)
        .strip()
        .lower()
    )


def clean_float(
    value: Any,
) -> float:
    """
    Convert an arbitrary value into a finite floating-point number.

    Invalid / NaN / +/- infinity values become 0.0.

    This function is intended primarily for FEATURES.

    Probability sanitisation itself is handled by
    temporal_fusion.normalise_probability_dict().
    """

    try:

        numeric = float(
            value
        )

        if np.isfinite(
            numeric
        ):

            return numeric

    except (
        TypeError,
        ValueError,
        OverflowError,
    ):

        pass

    return 0.0


def load_json_list(
    path: Path,
) -> list[str]:
    """
    Strictly load a JSON list of strings.
    """

    path = Path(
        path
    )

    if not path.exists():

        raise FileNotFoundError(
            f"JSON list file not found:\n{path}"
        )

    try:

        with path.open(
            "r",
            encoding="utf-8",
        ) as file_handle:

            value = json.load(
                file_handle
            )

    except Exception as exc:

        raise ValueError(
            f"Could not parse JSON list:\n{path}\n{exc}"
        ) from exc

    if not isinstance(
        value,
        list,
    ):

        raise ValueError(
            f"Expected a JSON list:\n{path}"
        )

    result = [
        str(item).strip()
        for item in value
    ]

    if any(
        not item
        for item in result
    ):

        raise ValueError(
            f"JSON list contains an empty value:\n{path}"
        )

    return result


def load_optional_json_object(
    path: Path,
) -> dict[str, Any]:
    """
    Load an optional JSON metadata object.

    Metadata is diagnostic only; absence does not prevent inference.
    """

    path = Path(
        path
    )

    if not path.exists():

        return {}

    try:

        with path.open(
            "r",
            encoding="utf-8",
        ) as file_handle:

            value = json.load(
                file_handle
            )

        if isinstance(
            value,
            dict,
        ):

            return value

    except Exception:

        pass

    return {}


def get_model_classes(
    model: Any,
) -> list[str]:
    """
    Obtain class ordering from a classifier or sklearn Pipeline.
    """

    classes = getattr(
        model,
        "classes_",
        None,
    )

    if classes is not None:

        return [
            normalise_label(
                label
            )
            for label in classes
        ]

    if hasattr(
        model,
        "named_steps",
    ):

        for step in reversed(
            list(
                model.named_steps.values()
            )
        ):

            classes = getattr(
                step,
                "classes_",
                None,
            )

            if classes is not None:

                return [
                    normalise_label(
                        label
                    )
                    for label in classes
                ]

    return []


def softmax(
    values: np.ndarray,
) -> np.ndarray:
    """
    Numerically stable softmax.

    Used only when a classifier provides decision_function(...)
    instead of predict_proba(...).
    """

    values = np.asarray(
        values,
        dtype=np.float64,
    ).reshape(
        -1
    )

    if values.size == 0:

        raise ValueError(
            "Cannot apply softmax to an empty score vector."
        )

    values = np.nan_to_num(
        values,
        nan=0.0,
        posinf=0.0,
        neginf=0.0,
    )

    values = (
        values
        - np.max(
            values
        )
    )

    exp_values = np.exp(
        values
    )

    total = float(
        np.sum(
            exp_values
        )
    )

    if (
        not np.isfinite(
            total
        )
        or
        total <= 0.0
    ):

        return (
            np.ones_like(
                exp_values,
                dtype=np.float64,
            )
            / len(
                exp_values
            )
        )

    return (
        exp_values
        / total
    )


