# =============================================================================
# COMMAND-LINE INTERFACE
# =============================================================================

def main() -> None:
    """
    Command-line entry point for ONE stateless multimodal prediction.

    Temporal fusion is intentionally not performed by this command.
    """

    parser = argparse.ArgumentParser(
        description=(
            "SenseFuzeAI canonical stateless multimodal "
            "behavioural-state inference pipeline. "
            "Temporal aggregation is performed separately by "
            "temporal_fusion.py."
        )
    )

    parser.add_argument(
        "--keystroke_json",
        required=True,
        type=Path,
        help=(
            "Path to a keystroke JSON containing "
            "a 'features' object."
        ),
    )

    parser.add_argument(
        "--text",
        required=True,
        type=str,
        help=(
            "Current text associated with this observation."
        ),
    )

    parser.add_argument(
        "--audio",
        required=True,
        type=Path,
        help=(
            "Path to the current audio source."
        ),
    )

    parser.add_argument(
        "--image",
        required=True,
        type=Path,
        help=(
            "Path to the current image or video/webcam snapshot."
        ),
    )

    parser.add_argument(
        "--output",
        default=None,
        type=Path,
        help=(
            "Optional JSON result output path."
        ),
    )

    args = (
        parser.parse_args()
    )

    inference = (
        FinalMultimodalInference()
    )

    result = (
        inference.predict(
            keystroke_json=(
                args.keystroke_json
            ),
            text=(
                args.text
            ),
            audio_path=(
                args.audio
            ),
            image_path=(
                args.image
            ),
        )
    )

    output_json = (
        json.dumps(
            result,
            indent=4,
        )
    )

    print()

    print(
        "=" * 80
    )

    print(
        "SenseFuzeAI "
        "Raw Multimodal Prediction"
    )

    print(
        "=" * 80
    )

    print(
        output_json
    )

    print()

    print(
        "NOTE: This is ONE raw multimodal observation. "
        "Temporal aggregation is applied externally "
        "by temporal_fusion.py."
    )

    if (
        args.output
        is not None
    ):

        args.output.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        args.output.write_text(
            output_json,
            encoding="utf-8",
        )

        print()

        print(
            "Prediction saved to:\n"
            f"{args.output}"
        )


# =============================================================================
# ENTRY POINT
# =============================================================================

if __name__ == "__main__":

    main()
