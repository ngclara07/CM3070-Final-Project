"""
final_multimodal_inference.py

SenseFuzeAI
Canonical Stateless Multimodal Behavioural-State Inference Pipeline

=============================================================================
PURPOSE
=============================================================================

This module performs ONE multimodal inference observation from:

    1. Keystroke dynamics
    2. MPNet text embeddings
    3. Librosa + WavLM audio features
    4. CLIP image embeddings
    5. Optional webcam-calibrated image probabilities

The resulting heterogeneous features are aligned to the exact feature
schema used to train the final fusion classifier.

This module intentionally DOES NOT maintain:

    - temporal probability history
    - rolling aggregation windows
    - temporal probability averaging
    - temporal generation state
    - reset behaviour

Those responsibilities belong exclusively to:

    temporal_fusion.py

Canonical architecture:

    current text
        |
    keystroke JSON
        |
    audio file
        |
    current image/frame
        |
        v
    FinalMultimodalInference.predict(...)
        |
        | ONE canonical raw probability vector
        v
    temporal_fusion.py
        |
        v
    desktop/web temporal result

=============================================================================
OUTPUT CONTRACT
=============================================================================

predict(...) returns exactly one four-class probability distribution:

    focused
    distracted
    fatigued
    overloaded

The probability distribution is:

    - finite
    - non-negative
    - restricted to the canonical four classes
    - normalised to sum to 1.0

The canonical current raw state is the argmax of that probability vector.

=============================================================================
WEBCAM-CALIBRATED IMAGE AUGMENTATION
=============================================================================

The current fusion model may require six additional image-derived features:

    image_webcam_focused_prob
    image_webcam_distracted_prob
    image_webcam_fatigued_prob
    image_webcam_overloaded_prob
    image_webcam_top_probability
    image_webcam_confidence_gap

These are generated by:

    models/image_demo/image_pipeline_webcam_calibrated.joblib

using the SAME CLIP embedding produced for the normal image branch.

The calibrated image model does not replace CLIP. It augments the fusion
feature vector.

=============================================================================
"""

